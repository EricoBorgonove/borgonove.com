export function copy(pt, en) {
  return { pt, en };
}

export function pick(value, isEn) {
  if (value && typeof value === "object" && "pt" in value && "en" in value) {
    return isEn ? value.en : value.pt;
  }
  return value;
}

export function localize(value, isEn) {
  if (Array.isArray(value)) {
    return value.map((item) => localize(item, isEn));
  }

  if (value && typeof value === "object") {
    if ("pt" in value && "en" in value) {
      return pick(value, isEn);
    }

    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, localize(item, isEn)])
    );
  }

  if (isEn && typeof value === "string") {
    return pandasTextMap[value] || value;
  }

  return value;
}

